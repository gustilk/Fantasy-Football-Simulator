#!/usr/bin/env python3
"""Derive historical game-participation rates by injury designation from free nflverse data.

Usage: python3 scripts/derive-availability-rates.py <dir-with-csvs> <first-season> <last-season>
The directory must hold injuries_<year>.csv, snaps_<year>.csv and players.csv downloaded from
https://github.com/nflverse/nflverse-data/releases (injuries, snap_counts and players releases).
Writes artifacts/gridiron-sim/src/lib/availability-rates.ts.

"Played" means the player recorded at least one offensive, defensive or special-teams snap in that
regular-season game. Injury rows without a matching snap-count identity are counted as NOT played only
when the player id links to a PFR id; rows with no id link are skipped, never guessed.
"""
import collections, csv, datetime, json, sys

src, first, last = sys.argv[1], int(sys.argv[2]), int(sys.argv[3])
POS = ('QB', 'RB', 'WR', 'TE')
gsis_to_pfr = {}
with open(f'{src}/players.csv', newline='', encoding='utf-8') as f:
    for r in csv.DictReader(f):
        if r['gsis_id'] and r['pfr_id']:
            gsis_to_pfr[r['gsis_id']] = r['pfr_id']

played = set()
for y in range(first, last + 1):
    with open(f'{src}/snaps_{y}.csv', newline='', encoding='utf-8') as f:
        for r in csv.DictReader(f):
            if r['game_type'] != 'REG':
                continue
            snaps = sum(float(r[k] or 0) for k in ('offense_snaps', 'defense_snaps', 'st_snaps'))
            if snaps > 0:
                played.add((int(r['season']), int(r['week']), r['pfr_player_id']))

counts = collections.defaultdict(lambda: [0, 0])  # (designation, position) -> [reports, played]
skipped = 0
for y in range(first, last + 1):
    with open(f'{src}/injuries_{y}.csv', newline='', encoding='utf-8') as f:
        for r in csv.DictReader(f):
            if r['game_type'] != 'REG' or r['position'] not in POS:
                continue
            status = r['report_status']
            if status in ('Out', 'Doubtful', 'Questionable'):
                key = status.lower()
            elif not status and 'Limited' in r['practice_status']:
                key = 'limited'  # limited in practice and never given a game designation
            else:
                continue
            pfr = gsis_to_pfr.get(r['gsis_id'])
            if not pfr:
                skipped += 1
                continue
            counts[(key, r['position'])][0] += 1
            counts[(key, r['position'])][1] += (int(r['season']), int(r['week']), pfr) in played

table = {k: {p: {'n': counts[(k, p)][0], 'played': counts[(k, p)][1]} for p in POS}
         for k in ('questionable', 'limited', 'doubtful', 'out')}
out = f"""// GENERATED by scripts/derive-availability-rates.py -- do not edit by hand.
// Historical share of players who recorded a snap, by injury designation and position.
// Source: nflverse injuries + snap_counts + players (free, no API key), regular seasons {first}-{last}.
// Generated {datetime.date.today().isoformat()}. {skipped} injury rows with no PFR id link were skipped.
// These are historical base rates, not a prediction for any individual player.
export const AVAILABILITY_RATE_SOURCE = 'nflverse injury reports + snap counts, regular seasons {first}-{last}';
export type RatedDesignation = 'questionable' | 'limited' | 'doubtful' | 'out';
export type RatedPosition = 'QB' | 'RB' | 'WR' | 'TE';
export const AVAILABILITY_COUNTS: Record<RatedDesignation, Record<RatedPosition, {{ n: number; played: number }}>> = {json.dumps(table, indent=2)};
"""
dest = 'artifacts/gridiron-sim/src/lib/availability-rates.ts'
open(dest, 'w').write(out)
print('wrote', dest)
